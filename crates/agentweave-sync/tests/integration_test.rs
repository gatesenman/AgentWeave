#[tokio::test]
async fn test_spawn_debounce_task() {
    let (input_tx, input_rx) = mpsc::unbounded_channel();
    let (output_tx, mut output_rx) = mpsc::unbounded_channel();

    let _handle = spawn_debounce_task(50, input_rx, output_tx);

    // Send a few events
    input_tx.send(PathBuf::from("/tmp/a.yaml")).unwrap();
    input_tx.send(PathBuf::from("/tmp/b.yaml")).unwrap();

    // Wait for debounce to fire
    sleep(Duration::from_millis(150)).await;

    let change = output_rx.try_recv();
    assert!(change.is_ok());
    let change = change.unwrap();
    assert_eq!(change.paths.len(), 2);
}

#[tokio::test]
async fn test_sync_engine_file_write_triggers_regeneration() {
    let tmp_dir = TempDir::new().unwrap();
    let project_root = tmp_dir.path().to_path_buf();
    setup_project(&project_root);

    // Build registry with mock adapter
    let mut registry = AdapterRegistry::new();
    registry.register(Box::new(MockAdapter::new()));
    let registry = Arc::new(Mutex::new(registry));

    let event_bus = shared_event_bus();
    let engine_config = SyncEngineConfig {
        project_root: project_root.clone(),
        debounce_ms: 50,
        lock_strategy: LockStrategy::LastWriteWins,
    };

    let engine = SyncEngine::new(engine_config, registry, event_bus.clone());

    let (shutdown_tx, shutdown_rx) = tokio::sync::watch::channel(false);

    // Subscribe to events
    let mut event_rx = event_bus.subscribe();

    // Start engine
    let engine_handle = tokio::spawn(async move {
        engine.run(shutdown_rx).await;
    });

    // Wait for watcher to start
    sleep(Duration::from_millis(200)).await;

    // Write a file change to trigger sync
    let agent_file = project_root.join(".agentweave/agents/main.agent.yaml");
    let updated_content = r#"name: main
description: "Updated test agent"
role: "Updated assistant"
systemPrompt: "You are an updated test assistant."
tools:
  allow: []
  deny: []
skills: []
"#;
    std::fs::write(&agent_file, updated_content).unwrap();

    // Wait for debounce + processing
    sleep(Duration::from_millis(500)).await;

    // Check that AGENTS.md was generated
    let output_file = project_root.join("AGENTS.md");
    assert!(output_file.exists(), "AGENTS.md should have been generated");

    let content = std::fs::read_to_string(&output_file).unwrap();
    assert!(content.contains("test-project"));

    // Check events were emitted
    let mut got_change = false;
    let mut got_success = false;
    while let Ok(event) = event_rx.try_recv() {
        match event {
            SyncEvent::ChangeDetected { .. } => got_change = true,
            SyncEvent::RegenerateSuccess { .. } => got_success = true,
            _ => {}
        }
    }
    assert!(got_change, "Should have received ChangeDetected event");
    assert!(got_success, "Should have received RegenerateSuccess event");

    // Shutdown
    let _ = shutdown_tx.send(true);
    let _ = engine_handle.await;
}
