/// A mock adapter that writes a simple output file
struct MockAdapter;

impl MockAdapter {
    fn new() -> Self {
        Self
    }
}

impl VendorAdapter for MockAdapter {
    fn vendor_id(&self) -> TargetVendor {
        TargetVendor::Codex
    }

    fn display_name(&self) -> &str {
        "Mock Codex"
    }

    fn generate(&self, config: &AgentWeaveConfig, _project_root: &Path) -> CoreResult<AdapterOutput> {
        let mut files = HashMap::new();
        let content = format!("# {}\nGenerated by mock adapter\n", config.metadata.name);
        files.insert("AGENTS.md".to_string(), content);
        Ok(AdapterOutput { files })
    }

    fn parse(&self, _project_root: &Path) -> CoreResult<AgentWeaveConfig> {
        unimplemented!()
    }

    fn supported_concepts(&self) -> Vec<Concept> {
        vec![Concept::Agent, Concept::Rule]
    }

    fn diff(&self, _config: &AgentWeaveConfig, _project_root: &Path) -> CoreResult<Vec<DiffEntry>> {
        Ok(vec![])
    }
}

fn setup_project(dir: &Path) {
    let config_dir = dir.join(".agentweave");
    std::fs::create_dir_all(config_dir.join("agents")).unwrap();
    std::fs::create_dir_all(config_dir.join("rules")).unwrap();

    let config_content = r#"apiVersion: agentweave/v1
kind: Project
metadata:
  name: "test-project"
  version: "0.1.0"

spec:
  targets:
    - codex
  sync:
    mode: realtime
    transport: file-watch
    lockStrategy: last-write-wins
"#;
    std::fs::write(config_dir.join("agentweave.yaml"), config_content).unwrap();

    let agent_content = r#"name: main
description: "Test agent"
role: "Assistant"
systemPrompt: "You are a test assistant."
tools:
  allow: []
  deny: []
skills: []
"#;
    std::fs::write(config_dir.join("agents/main.agent.yaml"), agent_content).unwrap();

    let rule_content = r#"name: general
description: "Test rule"
activation:
  type: always
content: "Follow best practices"
"#;
    std::fs::write(config_dir.join("rules/general.rule.yaml"), rule_content).unwrap();
}

