//! AgentWeave Adapter SDK
//!
//! This crate provides utilities and re-exports for building custom
//! vendor adapters for the AgentWeave platform.
//!
//! # Quick Start
//!
//! ```rust,ignore
//! use agentweave_sdk::prelude::*;
//! use agentweave_core::adapter::{Concept, DiffEntry};
//! use agentweave_core::error::Result;
//! use std::path::Path;
//!
//! pub struct MyVendorAdapter;
//!
//! impl VendorAdapter for MyVendorAdapter {
//!     fn vendor_id(&self) -> TargetVendor { TargetVendor::Codex }
//!     fn display_name(&self) -> &str { "My Vendor" }
//!     fn supported_concepts(&self) -> Vec<Concept> {
//!         vec![Concept::Agent, Concept::Rule, Concept::McpServer]
//!     }
//!     fn generate(&self, config: &AgentWeaveConfig, _root: &Path) -> Result<AdapterOutput> {
//!         let mut output = AdapterOutput { files: Default::default() };
//!         output.files.insert(".my-vendor/config.json".into(), "{}".into());
//!         Ok(output)
//!     }
//!     fn parse(&self, _root: &Path) -> Result<AgentWeaveConfig> { todo!() }
//!     fn diff(&self, _config: &AgentWeaveConfig, _root: &Path) -> Result<Vec<DiffEntry>> { todo!() }
//! }
//! ```

pub mod prelude {
    pub use agentweave_core::adapter::{AdapterOutput, VendorAdapter};
    pub use agentweave_core::config::AgentWeaveConfig;
    pub use agentweave_core::schema::TargetVendor;
    pub use anyhow::Result;
}

pub use agentweave_core::adapter;
pub use agentweave_core::config;
pub use agentweave_core::schema;

/// Helper to create an AdapterOutput with a single file
pub fn single_file_output(path: impl Into<String>, content: impl Into<String>) -> adapter::AdapterOutput {
    let mut files = std::collections::HashMap::new();
    files.insert(path.into(), content.into());
    adapter::AdapterOutput { files }
}

/// Helper to format a YAML comment header for generated files
pub fn generated_header(vendor_name: &str) -> String {
    format!(
        "# Generated by AgentWeave for {}\n# Do not edit manually - changes will be overwritten\n\n",
        vendor_name
    )
}
